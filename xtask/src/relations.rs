//! `cargo xtask relations` writes each language's generated enum.

use std::path::PathBuf;
use std::process::{Command, Stdio};
use std::{fmt, fs, io};

use extend::ext;
use thiserror::Error;

use crate::command_ext::{CommandError, CommandExt};

/// The languages with a generated enum, and the file each one goes to,
/// relative to `link-grammar/src/`.
const LANGUAGES: &[GeneratedLanguage] = &[GeneratedLanguage {
    code: "en",
    path: "english/relation.rs",
}];

/// A language whose enum `cargo xtask relations` writes.
struct GeneratedLanguage {
    code: &'static str,
    path: &'static str,
}

/// The generated relation enums of the workspace.
pub struct Relations {
    workspace: PathBuf,
}

impl Relations {
    /// The enums of the workspace at `workspace`.
    pub fn new(workspace: PathBuf) -> Self { Self { workspace } }

    /// Writes every language's enum.
    pub fn run(&self) -> Result<(), RelationsError> {
        LANGUAGES
            .iter()
            .try_for_each(|language| self.write(language))
    }

    /// Writes the enum of `language`, once each of its link types is a
    /// variant name.
    fn write(
        &self,
        language: &GeneratedLanguage,
    ) -> Result<(), RelationsError> {
        let code = language.code;
        let names = self.link_types(code)?;
        if let Some(name) =
            names.iter().find(|name| !name.is_variant_name())
        {
            return Err(RelationsError::BadName {
                code,
                name: name.clone(),
            });
        }
        let path =
            self.workspace.join("link-grammar/src").join(language.path);
        let file = RelationsFile {
            code,
            names: &names,
        };
        fs::write(&path, file.to_string())
            .map_err(|source| RelationsError::Write { path, source })
    }

    /// The link types of the `code` dictionary, in number order, as the
    /// `link_types` example prints them.
    fn link_types(
        &self,
        code: &str,
    ) -> Result<Vec<String>, RelationsError> {
        // stderr is inherited, as the library prints where it found the
        // dictionary.
        let example = Command::cargo()
            .current_dir(&self.workspace)
            .args(["run", "-q", "-p", "link-grammar-sys"])
            .args(["--example", "link_types", "--", code])
            .stderr(Stdio::inherit())
            .output_checked()?;
        Ok(String::from_utf8_lossy(&example.stdout)
            .lines()
            .map(str::to_owned)
            .collect())
    }
}

/// A generated file, which calls `link_relations!` with one variant per
/// link type.
struct RelationsFile<'a> {
    code: &'a str,
    names: &'a [String],
}

/// The file as rustfmt would leave it, which doesn't format the body of a
/// `{ }` macro call.
impl fmt::Display for RelationsFile<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let code = self.code;
        writeln!(
            f,
            "// @generated by `cargo xtask relations`. Don't edit.

link_relations! {{
    /// The link types of the `{code}` dictionary, one variant each, in
    /// link-grammar's numbering. The [English Link Documentation]
    /// describes each one.
    ///
    /// [English Link Documentation]: https://opencog.github.io/link-grammar-website/dict/index.html
    pub enum Relation {{"
        )?;
        for name in self.names {
            writeln!(f, "        \"{name}\" => {name},")?;
        }
        writeln!(f, "    }}\n}}")
    }
}

#[ext]
impl str {
    /// Whether the string is an uppercase ASCII letter, then uppercase
    /// letters and digits. Anything else would give a variant that
    /// doesn't compile or trips a lint.
    fn is_variant_name(&self) -> bool {
        self.starts_with(|c: char| c.is_ascii_uppercase())
            && self
                .bytes()
                .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit())
    }
}

/// Why `cargo xtask relations` stopped.
#[derive(Debug, Error)]
pub enum RelationsError {
    #[error(transparent)]
    Command(#[from] CommandError),
    #[error(
        "the `{code}` dictionary has link type `{name}`, which isn't a \
         variant name"
    )]
    BadName { code: &'static str, name: String },
    #[error("can't write {}: {source}", path.display())]
    Write { path: PathBuf, source: io::Error },
}
